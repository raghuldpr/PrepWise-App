// Generates apps/api/migrations/0003_seed_questions.sql from packages/content/src/*.json.
// Run: node scripts/build-seed.mjs   (re-run only before the migration has been applied anywhere;
// content added later should go into a NEW migration instead.)
import fs from "node:fs";

const read = (f) => JSON.parse(fs.readFileSync(new URL(`../packages/content/src/${f}`, import.meta.url), "utf8"));
const esc = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const row = (vals) => `(${vals.map(esc).join(", ")})`;

const companies = read("companies.json");
const { categories, questions } = read("questions.json");

const out = [];
out.push("-- GENERATED by scripts/build-seed.mjs from packages/content. Do not edit by hand.");
out.push("INSERT INTO companies (id, name, description, website, industry) VALUES\n" +
  companies.map((c) => row([c.id, c.name, c.description, c.website, c.industry])).join(",\n") + ";");
out.push("INSERT INTO question_categories (id, name, module_type, description) VALUES\n" +
  categories.map((c) => row([c.id, c.name, c.moduleType, c.description])).join(",\n") + ";");

const CHUNK = 25;
for (let i = 0; i < questions.length; i += CHUNK) {
  const part = questions.slice(i, i + CHUNK);
  out.push("INSERT INTO questions (id, category_id, company_id, title, question_text, difficulty, question_type, topic, expected_answer, explanation) VALUES\n" +
    part.map((q) => row([q.id, q.categoryId, q.companyId, q.title, q.questionText, q.difficulty, q.questionType, q.topic, q.expectedAnswer, q.explanation])).join(",\n") + ";");
  const opts = part.flatMap((q) => q.options.map((o) => `(${q.id}, ${esc(o.text)}, ${o.correct ? 1 : 0})`));
  out.push("INSERT INTO question_options (question_id, option_text, is_correct) VALUES\n" + opts.join(",\n") + ";");
}
fs.writeFileSync(new URL("../apps/api/migrations/0003_seed_questions.sql", import.meta.url), out.join("\n\n") + "\n");
console.log(`wrote ${questions.length} questions, ${questions.reduce((n, q) => n + q.options.length, 0)} options`);

// ---- Additional batches: each becomes its own migration (never edit an applied migration) ----
const EXTRA = [["questions-extra-1.json", "0004_more_questions.sql"]];
for (const [file, migration] of EXTRA) {
  const extra = read(file).questions;
  const parts = ["-- GENERATED by scripts/build-seed.mjs from packages/content/src/" + file + ". Do not edit by hand."];
  for (let i = 0; i < extra.length; i += CHUNK) {
    const part = extra.slice(i, i + CHUNK);
    parts.push("INSERT INTO questions (id, category_id, company_id, title, question_text, difficulty, question_type, topic, expected_answer, explanation) VALUES\n" +
      part.map((q) => row([q.id, q.categoryId, q.companyId, q.title, q.questionText, q.difficulty, q.questionType, q.topic, q.expectedAnswer, q.explanation])).join(",\n") + ";");
    parts.push("INSERT INTO question_options (question_id, option_text, is_correct) VALUES\n" +
      part.flatMap((q) => q.options.map((o) => `(${q.id}, ${esc(o.text)}, ${o.correct ? 1 : 0})`)).join(",\n") + ";");
  }
  fs.writeFileSync(new URL(`../apps/api/migrations/${migration}`, import.meta.url), parts.join("\n\n") + "\n");
  console.log(`wrote ${migration}: ${extra.length} questions`);
}
